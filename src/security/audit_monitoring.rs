//! Real-time audit monitoring and anomaly detection
//!
//! This module provides real-time monitoring of audit events, pattern detection,
//! and automated security response capabilities.

use anyhow::{anyhow, Result};
use chrono::{DateTime, Duration, Utc};
use serde::{Deserialize, Serialize};
use std::collections::{HashMap, VecDeque};
use std::sync::Arc;
use tokio::sync::{mpsc, RwLock};
use tracing::{error, info, warn};

use crate::security::audit_logging::{
    AuditEvent, AuditEventType, AuditOutcome, AuditSeverity, AuditSource,
};

/// Real-time audit monitor for security event analysis
pub struct AuditMonitor {
    /// Event receiver channel
    event_receiver: Arc<RwLock<Option<mpsc::UnboundedReceiver<AuditEvent>>>>,
    /// Pattern detectors
    pattern_detectors: Arc<RwLock<Vec<Box<dyn PatternDetector>>>>,
    /// Alert handlers
    alert_handlers: Arc<RwLock<Vec<Box<dyn AlertHandler>>>>,
    /// Event history for analysis
    event_history: Arc<RwLock<VecDeque<AuditEvent>>>,
    /// Monitoring configuration
    config: AuditMonitoringConfig,
    /// Current statistics
    statistics: Arc<RwLock<MonitoringStatistics>>,
    /// Active alerts
    active_alerts: Arc<RwLock<HashMap<String, SecurityAlert>>>,
}

/// Configuration for audit monitoring
#[derive(Debug, Clone)]
pub struct AuditMonitoringConfig {
    /// Maximum events to keep in history
    pub history_size: usize,
    /// Analysis window for pattern detection (seconds)
    pub analysis_window: u64,
    /// Threshold for failed authentication attempts
    pub failed_auth_threshold: u32,
    /// Time window for failed authentication attempts (seconds)
    pub failed_auth_window: u64,
    /// Threshold for suspicious IP activity
    pub ip_activity_threshold: u32,
    /// Threshold for privilege escalation attempts
    pub privilege_escalation_threshold: u32,
    /// Enable automated response
    pub enable_automated_response: bool,
    /// Alert cooldown period (seconds)
    pub alert_cooldown: u64,
    /// Maximum alerts per minute to prevent alert spam
    pub max_alerts_per_minute: u32,
}

impl Default for AuditMonitoringConfig {
    fn default() -> Self {
        Self {
            history_size: 10000,
            analysis_window: 300, // 5 minutes
            failed_auth_threshold: 5,
            failed_auth_window: 300, // 5 minutes
            ip_activity_threshold: 20,
            privilege_escalation_threshold: 3,
            enable_automated_response: true,
            alert_cooldown: 300, // 5 minutes
            max_alerts_per_minute: 10,
        }
    }
}

/// Pattern detector interface
pub trait PatternDetector: Send + Sync {
    /// Analyze events and detect patterns
    fn analyze(&self, events: &[AuditEvent]) -> Vec<SecurityAlert>;

    /// Get detector name
    fn name(&self) -> &'static str;

    /// Get detector priority
    fn priority(&self) -> u8 {
        1
    }
}

/// Alert handler interface
pub trait AlertHandler: Send + Sync {
    /// Handle security alert
    fn handle_alert(&self, alert: &SecurityAlert) -> Result<()>;

    /// Get handler name
    fn name(&self) -> &'static str;
}

/// Security alert generated by pattern detection
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SecurityAlert {
    /// Unique alert identifier
    pub id: String,
    /// Alert timestamp
    pub timestamp: DateTime<Utc>,
    /// Alert severity
    pub severity: AlertSeverity,
    /// Alert type/category
    pub alert_type: AlertType,
    /// Alert title
    pub title: String,
    /// Detailed description
    pub description: String,
    /// Source events that triggered the alert
    pub trigger_events: Vec<String>,
    /// Recommended actions
    pub recommended_actions: Vec<String>,
    /// Alert status
    pub status: AlertStatus,
    /// Additional alert data
    pub metadata: HashMap<String, String>,
}

/// Alert severity levels
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, Deserialize)]
pub enum AlertSeverity {
    Info,
    Low,
    Medium,
    High,
    Critical,
}

/// Alert types
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum AlertType {
    BruteForceAttack,
    SuspiciousActivity,
    PrivilegeEscalation,
    DataExfiltration,
    SystemCompromise,
    PolicyViolation,
    AnomalyDetection,
    SecurityMisconfiguration,
}

/// Alert status
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum AlertStatus {
    Active,
    Investigating,
    Resolved,
    FalsePositive,
    Suppressed,
}

/// Monitoring statistics
#[derive(Debug, Clone, Default)]
pub struct MonitoringStatistics {
    /// Total events processed
    pub total_events: u64,
    /// Events per second
    pub events_per_second: f64,
    /// Total alerts generated
    pub total_alerts: u64,
    /// Active alerts count
    pub active_alerts: u64,
    /// Events by type
    pub events_by_type: HashMap<AuditEventType, u64>,
    /// Events by severity
    pub events_by_severity: HashMap<AuditSeverity, u64>,
    /// Alerts by type
    pub alerts_by_type: HashMap<AlertType, u64>,
    /// Last update timestamp
    pub last_update: Option<DateTime<Utc>>,
}

impl AuditMonitor {
    /// Create new audit monitor
    pub fn new(config: AuditMonitoringConfig) -> Self {
        Self {
            event_receiver: Arc::new(RwLock::new(None)),
            pattern_detectors: Arc::new(RwLock::new(Vec::new())),
            alert_handlers: Arc::new(RwLock::new(Vec::new())),
            event_history: Arc::new(RwLock::new(VecDeque::new())),
            config,
            statistics: Arc::new(RwLock::new(MonitoringStatistics::default())),
            active_alerts: Arc::new(RwLock::new(HashMap::new())),
        }
    }

    /// Initialize monitoring with event channel
    pub async fn initialize(&mut self) -> Result<mpsc::UnboundedSender<AuditEvent>> {
        let (tx, rx) = mpsc::unbounded_channel();
        {
            let mut receiver = self.event_receiver.write().await;
            *receiver = Some(rx);
        }

        // Initialize default pattern detectors
        self.add_default_detectors().await;

        // Initialize default alert handlers
        self.add_default_handlers().await;

        // Start monitoring loop
        self.start_monitoring().await;

        Ok(tx)
    }

    /// Add pattern detector
    pub async fn add_detector(&self, detector: Box<dyn PatternDetector>) {
        let mut detectors = self.pattern_detectors.write().await;
        detectors.push(detector);

        // Sort by priority
        detectors.sort_by(|a, b| b.priority().cmp(&a.priority()));
    }

    /// Add alert handler
    pub async fn add_handler(&self, handler: Box<dyn AlertHandler>) {
        let mut handlers = self.alert_handlers.write().await;
        handlers.push(handler);
    }

    /// Get monitoring statistics
    pub async fn get_statistics(&self) -> MonitoringStatistics {
        let stats = self.statistics.read().await;
        stats.clone()
    }

    /// Get active alerts
    pub async fn get_active_alerts(&self) -> Vec<SecurityAlert> {
        let alerts = self.active_alerts.read().await;
        alerts.values().cloned().collect()
    }

    /// Acknowledge alert
    pub async fn acknowledge_alert(&self, alert_id: &str) -> Result<()> {
        let mut alerts = self.active_alerts.write().await;
        if let Some(alert) = alerts.get_mut(alert_id) {
            alert.status = AlertStatus::Investigating;
            info!("Alert {} acknowledged", alert_id);
        } else {
            return Err(anyhow!("Alert not found: {}", alert_id));
        }
        Ok(())
    }

    /// Resolve alert
    pub async fn resolve_alert(&self, alert_id: &str) -> Result<()> {
        let mut alerts = self.active_alerts.write().await;
        if let Some(alert) = alerts.remove(alert_id) {
            info!("Alert {} resolved: {}", alert_id, alert.title);
        } else {
            return Err(anyhow!("Alert not found: {}", alert_id));
        }
        Ok(())
    }

    /// Add default pattern detectors
    async fn add_default_detectors(&self) {
        // Brute force attack detector
        self.add_detector(Box::new(BruteForceDetector::new(&self.config)))
            .await;

        // Suspicious IP detector
        self.add_detector(Box::new(SuspiciousIPDetector::new(&self.config)))
            .await;

        // Privilege escalation detector
        self.add_detector(Box::new(PrivilegeEscalationDetector::new(&self.config)))
            .await;

        // Anomaly detector
        self.add_detector(Box::new(AnomalyDetector::new(&self.config)))
            .await;

        // Policy violation detector
        self.add_detector(Box::new(PolicyViolationDetector::new(&self.config)))
            .await;
    }

    /// Add default alert handlers
    async fn add_default_handlers(&self) {
        // Log alert handler
        self.add_handler(Box::new(LogAlertHandler::new())).await;

        // System response handler
        self.add_handler(Box::new(SystemResponseHandler::new()))
            .await;

        // Email alert handler (if configured)
        // self.add_handler(Box::new(EmailAlertHandler::new())).await;
    }

    /// Start monitoring loop
    async fn start_monitoring(&self) {
        let receiver = Arc::clone(&self.event_receiver);
        let history = Arc::clone(&self.event_history);
        let detectors = Arc::clone(&self.pattern_detectors);
        let handlers = Arc::clone(&self.alert_handlers);
        let statistics = Arc::clone(&self.statistics);
        let active_alerts = Arc::clone(&self.active_alerts);
        let config = self.config.clone();

        tokio::spawn(async move {
            let mut event_count = 0;
            let mut last_minute_count = 0;
            let mut last_minute_time = Utc::now();

            loop {
                // Get receiver and process events within the same scope
                let event = {
                    let mut rx_guard = receiver.write().await;
                    if let Some(ref mut rx) = *rx_guard {
                        rx.try_recv().ok()
                    } else {
                        None
                    }
                };

                if let Some(event) = event {
                    // Update statistics
                    {
                        let mut stats = statistics.write().await;
                        stats.total_events += 1;
                        *stats.events_by_type.entry(event.event_type).or_insert(0) += 1;
                        *stats.events_by_severity.entry(event.severity).or_insert(0) += 1;
                        stats.last_update = Some(Utc::now());

                        // Calculate events per second
                        let now = Utc::now();
                        if (now - last_minute_time).num_seconds() >= 60 {
                            stats.events_per_second = last_minute_count as f64 / 60.0;
                            last_minute_count = 0;
                            last_minute_time = now;
                        }
                        last_minute_count += 1;
                    }

                    // Add to history
                    {
                        let mut hist = history.write().await;
                        hist.push_back(event.clone());

                        // Maintain history size
                        while hist.len() > config.history_size {
                            hist.pop_front();
                        }
                    }

                    // Run pattern detection
                    let current_events = {
                        let hist = history.read().await;
                        hist.iter().cloned().collect::<Vec<_>>()
                    };

                    let current_detectors = detectors.read().await;
                    let mut alerts = Vec::new();

                    for detector in current_detectors.iter() {
                        let mut detector_alerts = detector.analyze(&current_events);
                        alerts.append(&mut detector_alerts);
                    }

                    // Process alerts
                    if !alerts.is_empty() {
                        let mut alert_count = 0;
                        for alert in alerts {
                            // Check cooldown
                            if Self::should_send_alert(&alert, &active_alerts, &config).await {
                                // Add to active alerts
                                {
                                    let mut alerts_map = active_alerts.write().await;
                                    alerts_map.insert(alert.id.clone(), alert.clone());
                                }

                                // Handle alert
                                let current_handlers = handlers.read().await;
                                for handler in current_handlers.iter() {
                                    if let Err(e) = handler.handle_alert(&alert) {
                                        error!("Alert handler {} failed: {}", handler.name(), e);
                                    }
                                }

                                alert_count += 1;
                            }

                            // Rate limit alerts
                            if alert_count >= config.max_alerts_per_minute {
                                warn!("Alert rate limit reached, suppressing further alerts");
                                break;
                            }
                        }
                    }
                }

                // No event received, sleep briefly
                tokio::time::sleep(tokio::time::Duration::from_millis(100)).await;
            }
        });
    }

    /// Check if alert should be sent (cooldown and duplicate checks)
    async fn should_send_alert(
        &self,
        alert: &SecurityAlert,
        active_alerts: &Arc<RwLock<HashMap<String, SecurityAlert>>>,
        config: &AuditMonitoringConfig,
    ) -> bool {
        let alerts = active_alerts.read().await;

        // Check for similar active alerts
        for existing_alert in alerts.values() {
            if existing_alert.alert_type == alert.alert_type
                && existing_alert.status == AlertStatus::Active
                && (alert.timestamp - existing_alert.timestamp).num_seconds()
                    < config.alert_cooldown as i64
            {
                return false; // Suppress duplicate alert
            }
        }

        true
    }
}

/// Brute force attack detector
pub struct BruteForceDetector {
    config: AuditMonitoringConfig,
}

impl BruteForceDetector {
    pub fn new(config: &AuditMonitoringConfig) -> Self {
        Self {
            config: config.clone(),
        }
    }
}

impl PatternDetector for BruteForceDetector {
    fn analyze(&self, events: &[AuditEvent]) -> Vec<SecurityAlert> {
        let mut alerts = Vec::new();
        let now = Utc::now();
        let window_start = now - Duration::seconds(self.config.failed_auth_window as i64);

        // Group failed authentication attempts by source
        let mut auth_failures: HashMap<String, Vec<&AuditEvent>> = HashMap::new();

        for event in events {
            if event.event_type == AuditEventType::Authentication
                && event.outcome == AuditOutcome::Failure
                && event.timestamp > window_start
            {
                let key = format!(
                    "{}:{}",
                    event.source.identifier,
                    event.source.ip_address.as_deref().unwrap_or("unknown")
                );
                auth_failures
                    .entry(key)
                    .or_insert_with(Vec::new)
                    .push(event);
            }
        }

        // Check for brute force patterns
        for (source, failures) in auth_failures {
            if failures.len() as u32 >= self.config.failed_auth_threshold {
                let alert = SecurityAlert {
                    id: uuid::Uuid::new_v4().to_string(),
                    timestamp: now,
                    severity: if failures.len() >= 10 {
                        AlertSeverity::High
                    } else {
                        AlertSeverity::Medium
                    },
                    alert_type: AlertType::BruteForceAttack,
                    title: "Potential Brute Force Attack Detected".to_string(),
                    description: format!(
                        "{} failed authentication attempts from {} in the last {} seconds",
                        failures.len(),
                        source,
                        self.config.failed_auth_window
                    ),
                    trigger_events: failures.iter().map(|e| e.id.clone()).collect(),
                    recommended_actions: vec![
                        "Block source IP address".to_string(),
                        "Lock affected user accounts".to_string(),
                        "Investigate source of attacks".to_string(),
                    ],
                    status: AlertStatus::Active,
                    metadata: {
                        let mut meta = HashMap::new();
                        meta.insert("source".to_string(), source);
                        meta.insert("failure_count".to_string(), failures.len().to_string());
                        meta
                    },
                };
                alerts.push(alert);
            }
        }

        alerts
    }

    fn name(&self) -> &'static str {
        "brute_force_detector"
    }

    fn priority(&self) -> u8 {
        10 // High priority
    }
}

/// Suspicious IP activity detector
pub struct SuspiciousIPDetector {
    config: AuditMonitoringConfig,
}

impl SuspiciousIPDetector {
    pub fn new(config: &AuditMonitoringConfig) -> Self {
        Self {
            config: config.clone(),
        }
    }
}

impl PatternDetector for SuspiciousIPDetector {
    fn analyze(&self, events: &[AuditEvent]) -> Vec<SecurityAlert> {
        let mut alerts = Vec::new();
        let now = Utc::now();
        let window_start = now - Duration::seconds(self.config.analysis_window as i64);

        // Group events by IP address
        let mut ip_activities: HashMap<String, Vec<&AuditEvent>> = HashMap::new();

        for event in events {
            if event.timestamp > window_start {
                if let Some(ip) = &event.source.ip_address {
                    ip_activities
                        .entry(ip.clone())
                        .or_insert_with(Vec::new)
                        .push(event);
                }
            }
        }

        // Check for suspicious activity patterns
        for (ip, ip_events) in ip_activities {
            if ip_events.len() as u32 >= self.config.ip_activity_threshold {
                // Analyze event types
                let mut event_types = std::collections::HashSet::new();
                let mut failed_attempts = 0;
                let mut security_violations = 0;

                for event in &ip_events {
                    event_types.insert(event.event_type);
                    match event.outcome {
                        AuditOutcome::Failure => failed_attempts += 1,
                        AuditOutcome::Blocked => failed_attempts += 1,
                        _ => {}
                    }
                    if event.event_type == AuditEventType::SecurityViolation {
                        security_violations += 1;
                    }
                }

                // Determine alert severity
                let severity = if security_violations > 0 || failed_attempts > ip_events.len() / 2 {
                    AlertSeverity::High
                } else {
                    AlertSeverity::Medium
                };

                let alert = SecurityAlert {
                    id: uuid::Uuid::new_v4().to_string(),
                    timestamp: now,
                    severity,
                    alert_type: AlertType::SuspiciousActivity,
                    title: "Suspicious IP Activity Detected".to_string(),
                    description: format!(
                        "High activity from IP {}: {} events in {} seconds ({} unique types, {} failures)",
                        ip,
                        ip_events.len(),
                        self.config.analysis_window,
                        event_types.len(),
                        failed_attempts
                    ),
                    trigger_events: ip_events.iter().map(|e| e.id.clone()).collect(),
                    recommended_actions: vec![
                        "Investigate IP reputation".to_string(),
                        "Consider blocking IP address".to_string(),
                        "Review all activities from this IP".to_string(),
                    ],
                    status: AlertStatus::Active,
                    metadata: {
                        let mut meta = HashMap::new();
                        meta.insert("ip_address".to_string(), ip);
                        meta.insert("event_count".to_string(), ip_events.len().to_string());
                        meta.insert("failed_attempts".to_string(), failed_attempts.to_string());
                        meta.insert("security_violations".to_string(), security_violations.to_string());
                        meta
                    },
                };
                alerts.push(alert);
            }
        }

        alerts
    }

    fn name(&self) -> &'static str {
        "suspicious_ip_detector"
    }

    fn priority(&self) -> u8 {
        8
    }
}

/// Privilege escalation detector
pub struct PrivilegeEscalationDetector {
    config: AuditMonitoringConfig,
}

impl PrivilegeEscalationDetector {
    pub fn new(config: &AuditMonitoringConfig) -> Self {
        Self {
            config: config.clone(),
        }
    }
}

impl PatternDetector for PrivilegeEscalationDetector {
    fn analyze(&self, events: &[AuditEvent]) -> Vec<SecurityAlert> {
        let mut alerts = Vec::new();
        let now = Utc::now();
        let window_start = now - Duration::seconds(self.config.analysis_window as i64);

        // Group administrative actions by user
        let mut admin_actions: HashMap<String, Vec<&AuditEvent>> = HashMap::new();

        for event in events {
            if event.timestamp > window_start
                && (event.event_type == AuditEventType::AdministrativeAction
                    || event.event_type == AuditEventType::ConfigurationChange
                    || event.event_type == AuditEventType::SecurityPolicy)
            {
                admin_actions
                    .entry(event.source.identifier.clone())
                    .or_insert_with(Vec::new)
                    .push(event);
            }
        }

        // Check for privilege escalation patterns
        for (user, actions) in admin_actions {
            if actions.len() as u32 >= self.config.privilege_escalation_threshold {
                // Analyze action types
                let mut policy_changes = 0;
                let mut config_changes = 0;
                let mut security_changes = 0;

                for action in &actions {
                    match action.event_type {
                        AuditEventType::SecurityPolicy => security_changes += 1,
                        AuditEventType::ConfigurationChange => config_changes += 1,
                        AuditEventType::AdministrativeAction => policy_changes += 1,
                        _ => {}
                    }
                }

                let alert = SecurityAlert {
                    id: uuid::Uuid::new_v4().to_string(),
                    timestamp: now,
                    severity: AlertSeverity::High,
                    alert_type: AlertType::PrivilegeEscalation,
                    title: "Potential Privilege Escalation Detected".to_string(),
                    description: format!(
                        "User {} performed {} administrative actions in {} seconds ({} security, {} config, {} admin)",
                        user,
                        actions.len(),
                        self.config.analysis_window,
                        security_changes,
                        config_changes,
                        policy_changes
                    ),
                    trigger_events: actions.iter().map(|e| e.id.clone()).collect(),
                    recommended_actions: vec![
                        "Review user permissions".to_string(),
                        "Verify all changes made by user".to_string(),
                        "Consider temporary privilege suspension".to_string(),
                    ],
                    status: AlertStatus::Active,
                    metadata: {
                        let mut meta = HashMap::new();
                        meta.insert("user".to_string(), user);
                        meta.insert("action_count".to_string(), actions.len().to_string());
                        meta.insert("security_changes".to_string(), security_changes.to_string());
                        meta
                    },
                };
                alerts.push(alert);
            }
        }

        alerts
    }

    fn name(&self) -> &'static str {
        "privilege_escalation_detector"
    }

    fn priority(&self) -> u8 {
        9
    }
}

/// Anomaly detector using statistical analysis
pub struct AnomalyDetector {
    config: AuditMonitoringConfig,
}

impl AnomalyDetector {
    pub fn new(config: &AuditMonitoringConfig) -> Self {
        Self {
            config: config.clone(),
        }
    }
}

impl PatternDetector for AnomalyDetector {
    fn analyze(&self, events: &[AuditEvent]) -> Vec<SecurityAlert> {
        let mut alerts = Vec::new();

        // Analyze event frequency patterns
        let mut hourly_counts = HashMap::new();
        let now = Utc::now();

        for event in events {
            let hour_key = event.timestamp.format("%Y-%m-%d-%H").to_string();
            *hourly_counts.entry(hour_key).or_insert(0) += 1;
        }

        // Calculate baseline (average of past hours)
        if hourly_counts.len() > 1 {
            let counts: Vec<u32> = hourly_counts.values().cloned().collect();
            let mean = counts.iter().sum::<u32>() as f64 / counts.len() as f64;
            let std_dev = {
                let variance = counts
                    .iter()
                    .map(|&x| (x as f64 - mean).powi(2))
                    .sum::<f64>()
                    / counts.len() as f64;
                variance.sqrt()
            };

            // Check for anomalies (3 standard deviations from mean)
            for (hour, count) in hourly_counts {
                if (count as f64 - mean).abs() > 3.0 * std_dev {
                    let alert = SecurityAlert {
                        id: uuid::Uuid::new_v4().to_string(),
                        timestamp: now,
                        severity: AlertSeverity::Medium,
                        alert_type: AlertType::AnomalyDetection,
                        title: "Unusual Activity Pattern Detected".to_string(),
                        description: format!(
                            "Anomalous event count detected for hour {}: {} events (baseline: {:.1} ± {:.1})",
                            hour, count, mean, std_dev
                        ),
                        trigger_events: vec![],
                        recommended_actions: vec![
                            "Investigate unusual activity".to_string(),
                            "Check for system issues or attacks".to_string(),
                        ],
                        status: AlertStatus::Active,
                        metadata: {
                            let mut meta = HashMap::new();
                            meta.insert("hour".to_string(), hour);
                            meta.insert("event_count".to_string(), count.to_string());
                            meta.insert("baseline_mean".to_string(), format!("{:.1}", mean));
                            meta.insert("baseline_stddev".to_string(), format!("{:.1}", std_dev));
                            meta
                        },
                    };
                    alerts.push(alert);
                }
            }
        }

        alerts
    }

    fn name(&self) -> &'static str {
        "anomaly_detector"
    }

    fn priority(&self) -> u8 {
        5
    }
}

/// Policy violation detector
pub struct PolicyViolationDetector {
    config: AuditMonitoringConfig,
}

impl PolicyViolationDetector {
    pub fn new(config: &AuditMonitoringConfig) -> Self {
        Self {
            config: config.clone(),
        }
    }
}

impl PatternDetector for PolicyViolationDetector {
    fn analyze(&self, events: &[AuditEvent]) -> Vec<SecurityAlert> {
        let mut alerts = Vec::new();
        let now = Utc::now();

        // Look for specific policy violations
        for event in events {
            match event.event_type {
                AuditEventType::SecurityViolation => {
                    let alert = SecurityAlert {
                        id: uuid::Uuid::new_v4().to_string(),
                        timestamp: now,
                        severity: AlertSeverity::High,
                        alert_type: AlertType::PolicyViolation,
                        title: "Security Policy Violation".to_string(),
                        description: format!("Security policy violation: {}", event.description),
                        trigger_events: vec![event.id.clone()],
                        recommended_actions: vec![
                            "Review security policies".to_string(),
                            "Investigate violation cause".to_string(),
                            "Consider disciplinary action".to_string(),
                        ],
                        status: AlertStatus::Active,
                        metadata: {
                            let mut meta = HashMap::new();
                            meta.insert(
                                "violation_type".to_string(),
                                "security_policy".to_string(),
                            );
                            meta
                        },
                    };
                    alerts.push(alert);
                }
                AuditEventType::Authentication => {
                    // Check for authentication from unusual locations
                    if let Some(ref ip) = event.source.ip_address {
                        if self.is_unusual_location(ip) {
                            let alert = SecurityAlert {
                                id: uuid::Uuid::new_v4().to_string(),
                                timestamp: now,
                                severity: AlertSeverity::Medium,
                                alert_type: AlertType::PolicyViolation,
                                title: "Authentication from Unusual Location".to_string(),
                                description: format!(
                                    "Authentication event from potentially unusual IP address: {}",
                                    ip
                                ),
                                trigger_events: vec![event.id.clone()],
                                recommended_actions: vec![
                                    "Verify user location".to_string(),
                                    "Consider multi-factor authentication".to_string(),
                                ],
                                status: AlertStatus::Active,
                                metadata: {
                                    let mut meta = HashMap::new();
                                    meta.insert("ip_address".to_string(), ip.clone());
                                    meta
                                },
                            };
                            alerts.push(alert);
                        }
                    }
                }
                _ => {}
            }
        }

        alerts
    }

    fn name(&self) -> &'static str {
        "policy_violation_detector"
    }

    fn priority(&self) -> u8 {
        7
    }
}

impl AnomalyDetector {
    fn is_unusual_location(&self, ip: &str) -> bool {
        // Simple heuristic for unusual locations
        // In a real implementation, this would use geolocation or known good IPs
        ip.starts_with("10.") || // Check for internal IP
        ip.starts_with("192.168.") ||
        ip.starts_with("172.") ||
        ip == "127.0.0.1" ||
        ip == "::1"
    }
}

/// Log alert handler
pub struct LogAlertHandler {
    _private: (),
}

impl LogAlertHandler {
    pub fn new() -> Self {
        Self { _private: () }
    }
}

impl AlertHandler for LogAlertHandler {
    fn handle_alert(&self, alert: &SecurityAlert) -> Result<()> {
        let severity_str = match alert.severity {
            AlertSeverity::Info => "INFO",
            AlertSeverity::Low => "LOW",
            AlertSeverity::Medium => "MEDIUM",
            AlertSeverity::High => "HIGH",
            AlertSeverity::Critical => "CRITICAL",
        };

        error!(
            "[SECURITY ALERT] [{}] {}: {}",
            severity_str, alert.title, alert.description
        );

        for action in &alert.recommended_actions {
            info!("  Recommended action: {}", action);
        }

        Ok(())
    }

    fn name(&self) -> &'static str {
        "log_alert_handler"
    }
}

